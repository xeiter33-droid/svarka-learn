const fs = require("fs");
const path = require("path");

function clean(raw) {
  return String(raw || "")
    .replace(/\r/g, "")
    .replace(/\d{10,}/g, "")
    .replace(/([А-Яа-яA-Za-z])-\n([а-яa-z])/g, "$1$2")
    .replace(/\n{3,}/g, "\n\n")
    .replace(/[^\S\n]{2,}/g, " ")
    .trim();
}

function paras(raw, n = 5) {
  return clean(raw)
    .split(/\n+/)
    .map((p) => p.trim())
    .filter((p) => p.length > 40 && !/^Рис\./i.test(p) && !/^\d+$/.test(p) && !/^Глава\s+\d/i.test(p))
    .slice(0, n);
}

function html(parts, extra = "") {
  const body = (Array.isArray(parts) ? parts : paras(parts, 6))
    .map((p) => `<p>${p}</p>`)
    .join("\n");
  return body + (extra || "");
}

function note(text) {
  return `<div class="lesson-note"><strong>Норматив / пособие.</strong> ${text}</div>`;
}

function Q(id, q, options, answer) {
  return { id, q, options, answer };
}

